// scripts/build.js
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC_DIR = path.join(ROOT, "src");
const DIST_DIR = path.join(ROOT, "dist");
const ORDER_FILE = path.join(SRC_DIR, "install-order.txt");
const PLACEHOLDER = /\$\(SchemaName\)/g;

const SCHEMAS = ["mold", "m"];

function replaceSchema(content, schemaName) {
  return content.replace(PLACEHOLDER, () => schemaName);
}

function readOrder() {
  if (!fs.existsSync(ORDER_FILE)) {
    throw new Error(
      `Missing ${ORDER_FILE}. It must list source files, one per line, in dependency order.`,
    );
  }
  return fs
    .readFileSync(ORDER_FILE, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
}

function buildForSchema(schemaName, files) {
  const parts = [];

  parts.push(`-- =============================================`);
  parts.push(`-- DbMold install script — schema: ${schemaName}`);
  parts.push(`-- Generated by build.js. Do not edit by hand.`);
  parts.push(`-- =============================================`);
  parts.push("");

  for (const relPath of files) {
    const absPath = path.join(SRC_DIR, relPath);
    if (!fs.existsSync(absPath)) {
      throw new Error(`Source file not found: ${absPath}`);
    }
    const raw = fs.readFileSync(absPath, "utf8");
    const replaced = replaceSchema(raw, schemaName);

    parts.push(`-- ---------------------------------------------`);
    parts.push(`-- ${relPath}`);
    parts.push(`-- ---------------------------------------------`);
    parts.push(replaced.trimEnd());
    parts.push("");
  }

  return parts.join("\n");
}

function buildAll() {
  if (!fs.existsSync(DIST_DIR)) {
    fs.mkdirSync(DIST_DIR, { recursive: true });
  }

  const files = readOrder();

  for (const schema of SCHEMAS) {
    const content = buildForSchema(schema, files);
    const outPath = path.join(DIST_DIR, `install-${schema}.sql`);
    fs.writeFileSync(outPath, content, "utf8");
    console.log(
      `Generated ${path.relative(ROOT, outPath)} (${content.length} bytes, ${files.length} files)`,
    );
  }
}

module.exports = { buildAll, SCHEMAS };
